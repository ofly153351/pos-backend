# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def esc(s: str) -> str:
    """Escape a string literal for SQL."""
    return s.replace("'", "''")


def ean13(i: int) -> str:
    """Deterministic 13-digit EAN-like barcode starting with 885."""
    return f"885{1000000000 + i}"


# ---------------------------------------------------------------------------
# SQL generation
# ---------------------------------------------------------------------------

def build_sql(store_id: str, with_stock: bool) -> str:
    lines = ["BEGIN;"]

    # id counters
    cat_id = {}
    unit_id = {}
    brand_id = {}

    # ── categories ──
    for i, (name, desc, _prefix) in enumerate(CATEGORIES, 1):
        cid = f"ptype-seed-{i:02d}"
        cat_id[name] = cid
        lines.append(
            "INSERT INTO product_types (id, store_id, name, description, is_active, created_at, updated_at) "
            f"VALUES ('{cid}', '{store_id}', '{esc(name)}', '{esc(desc)}', TRUE, NOW(), NOW()) "
            "ON CONFLICT DO NOTHING;"
        )

    # ── units ──
    for i, name in enumerate(UNITS, 1):
        uid = f"punit-seed-{i:02d}"
        unit_id[name] = uid
        lines.append(
            "INSERT INTO product_units (id, store_id, name, description, is_active, created_at, updated_at) "
            f"VALUES ('{uid}', '{store_id}', '{esc(name)}', '', TRUE, NOW(), NOW()) "
            "ON CONFLICT DO NOTHING;"
        )

    # ── brands ──
    for i, name in enumerate(BRANDS, 1):
        bid = f"brand-seed-{i:02d}"
        brand_id[name] = bid
        lines.append(
            "INSERT INTO product_brands (id, store_id, name, is_active, created_at, updated_at) "
            f"VALUES ('{bid}', '{store_id}', '{esc(name)}', TRUE, NOW(), NOW()) "
            "ON CONFLICT DO NOTHING;"
        )

    # ── products ──
    sku_seq: dict[str, int] = {}
    prefix_map = {name: prefix for name, _desc, prefix in CATEGORIES}
    for i, (name, cat, unit, brand, price) in enumerate(PRODUCTS):
        if cat not in cat_id:
            sys.exit(f"ERROR: product '{name}' references unknown category '{cat}'")
        if unit not in unit_id:
            sys.exit(f"ERROR: product '{name}' references unknown unit '{unit}'")
        if brand not in brand_id:
            sys.exit(f"ERROR: product '{name}' references unknown brand '{brand}'")

        prefix = prefix_map[cat]
        seq = sku_seq.get(prefix, 0) + 1
        sku_seq[prefix] = seq
        sku = f"{prefix}-{seq:03d}"
        barcode = ean13(i + 1)
        pid = f"pd-seed-{i + 1:04d}"
        cost = round(price * 0.62, 2)

        lines.append(
            "INSERT INTO products "
            "(id, store_id, product_type_id, product_unit_id, brand_id, name, sku, barcode, "
            "base_price, cost_price, min_stock, is_active, created_at, updated_at) "
            f"VALUES ('{pid}', '{store_id}', '{cat_id[cat]}', '{unit_id[unit]}', '{brand_id[brand]}', "
            f"'{esc(name)}', '{sku}', '{barcode}', {price}, {cost}, 20, TRUE, NOW(), NOW()) "
            "ON CONFLICT DO NOTHING;"
        )

        # ── optional stock at the sale location ──
        if with_stock:
            lines.append(
                "INSERT INTO stocks (id, store_id, product_id, location_id, quantity, created_at, updated_at) "
                f"SELECT 'stk-seed-{i + 1:04d}', '{store_id}', '{pid}', l.id, 60, NOW(), NOW() "
                f"FROM locations l WHERE l.store_id = '{store_id}' AND l.is_sale_point = TRUE LIMIT 1 "
                "ON CONFLICT (product_id, location_id) DO NOTHING;"
            )

    lines.append("COMMIT;")
    return "\n".join(lines) + "\n"


