def container_env(container: str, var: str) -> str:
    r = subprocess.run(
        ["docker", "exec", container, "printenv", var],
        capture_output=True, text=True,
    )
    return r.stdout.strip()


def run_psql(sql: str, container: str, db_user: str, db_name: str) -> int:
    cmd = ["docker", "exec", "-i", container, "psql",
           "-U", db_user, "-d", db_name, "-v", "ON_ERROR_STOP=1"]
    r = subprocess.run(cmd, input=sql, text=True, capture_output=True)
    sys.stdout.write(r.stdout)
    if r.stderr:
        sys.stderr.write(r.stderr)
    return r.returncode


def main() -> int:
    p = argparse.ArgumentParser(description="Seed demo catalog (types/units/brands + 200+ products)")
    p.add_argument("--sql", action="store_true", help="print SQL only, do not touch the DB")
    p.add_argument("--with-stock", action="store_true", help="also seed 60 units of stock at the sale location")
    p.add_argument("--store-id", default=os.environ.get("POS_STORE_ID", "str-00000001"))
    p.add_argument("--container", default=os.environ.get("POS_PG_CONTAINER", "pos-backend-postgres-1"))
    p.add_argument("--db-user", default=os.environ.get("POS_DB_USER", ""))
    p.add_argument("--db-name", default=os.environ.get("POS_DB_NAME", ""))
    args = p.parse_args()

    sql = build_sql(args.store_id, args.with_stock)

    if args.sql:
        sys.stdout.write(sql)
        print(f"\n-- Generated {len(PRODUCTS)} products, {len(CATEGORIES)} categories, "
              f"{len(UNITS)} units, {len(BRANDS)} brands for store {args.store_id}", file=sys.stderr)
        return 0

    db_user = args.db_user or container_env(args.container, "POSTGRES_USER") or "postgres"
    db_name = args.db_name or container_env(args.container, "POSTGRES_DB") or "pos_db"

    print(f"Target: {args.container}  ({db_user}@{db_name})  store={args.store_id}")
    rc = run_psql(sql, args.container, db_user, db_name)
    if rc != 0:
        print("ERROR: psql exited non-zero", file=sys.stderr)
        return rc

    # summary counts
    print(f"\nDone — seeded catalog for store {args.store_id} "
          f"({len(PRODUCTS)} products, {len(CATEGORIES)} categories, {len(UNITS)} units, "
          f"{len(BRANDS)} brands). Re-running is a no-op (ON CONFLICT DO NOTHING).")
    summary_sql = (
        f"SELECT (SELECT count(*) FROM product_types WHERE store_id = '{esc(args.store_id)}') AS types, "
        f"       (SELECT count(*) FROM product_units  WHERE store_id = '{esc(args.store_id)}') AS units, "
        f"       (SELECT count(*) FROM product_brands WHERE store_id = '{esc(args.store_id)}') AS brands, "
        f"       (SELECT count(*) FROM products      WHERE store_id = '{esc(args.store_id)}') AS products;"
    )
    return run_psql(summary_sql, args.container, db_user, db_name)


if __name__ == "__main__":
    raise SystemExit(main())
